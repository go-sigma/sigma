// Self handles the self get request
func (h *handler) SelfGet(c *gin.Context) {
	user, ok := utils.GetFromCtx[*models.User](c, consts.ContextUser)
	if !ok {
		slog.Error("get user from context failed")
		errcode.NewHTTPError(c, errcode.HTTPErrCodeUnauthorized)
		return
	}
	c.JSON(http.StatusOK, api.GetUserSelfResponse{
		ID:       user.ID,
		Username: user.Username,
		Email:    ptr.To(user.Email),
		Role:     user.Role,
	})
}
